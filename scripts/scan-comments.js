#!/usr/bin/env node
// Audits existing files against the comment budget the PreToolUse hook enforces.
// Usage: node scan-comments.js <root> [<root>...] [--json out.json] [--top N]

const fs = require('fs');
const path = require('path');
const budget = require('./hooks/comment-budget-guard.js');

// Only names that are never hand-written source. Words like assets, public, lib
// and examples are real source directories in some repos, so they are judged by
// looksGenerated() instead of by name.
const SKIP_DIR = new Set([
  '.git', 'node_modules', 'dist', 'build', 'vendor', '.venv', 'venv',
  '__pycache__', '.next', 'coverage', 'site-packages', '.pytest_cache', 'docs',
  '.mypy_cache', 'target', '.turbo', 'htmlcov', '.tox', 'third_party',
  'external', 'migrations',
  '.cache', 'bower_components', 'generated', '__generated__', 'outputs',
  'AppData', 'Downloads', 'OneDrive', 'Documents', 'Desktop', 'catboost_info',
  'worktrees', 'repo-runs',
]);
const SKIP_FILE = /\.(min|bundle|generated|pb|_pb2)\./i;
// Numbered SQL files are applied migrations. Editing one rewrites history.
const SKIP_MIGRATION = /^\d{2,}[_-].*\.sql$/i;
const GENERATED_MARK = /@generated|DO NOT EDIT|should not be edited|Code generated by|auto-generated|sourceMappingURL/i;
const MAX_BYTES = 2_000_000;
const MAX_LINE = 500;

// Bundled and generated files carry banner comments nobody wrote by hand.
function looksGenerated(text) {
  if (GENERATED_MARK.test(text.slice(0, 4000))) return true;
  return text.split(/\r?\n/).some((l) => l.length > MAX_LINE);
}

function isWorktree(dir) {
  try { return fs.statSync(path.join(dir, '.git')).isFile(); } catch { return false; }
}

function walk(root, out) {
  let entries;
  try { entries = fs.readdirSync(root, { withFileTypes: true }); } catch { return; }
  for (const e of entries) {
    const full = path.join(root, e.name);
    if (e.isDirectory()) {
      if (SKIP_DIR.has(e.name) || e.name.startsWith('.')) continue;
      // A .git FILE means a linked worktree: same code as its main clone, so skip it.
      if (isWorktree(full)) continue;
      walk(full, out);
    } else if (e.isFile()) {
      const ext = path.extname(e.name).slice(1).toLowerCase();
      if (!budget.LINE_TOKENS[ext] || SKIP_FILE.test(e.name)) continue;
      if (SKIP_MIGRATION.test(e.name)) continue;
      out.push(full);
    }
  }
}

function grade(file) {
  let stat;
  try { stat = fs.statSync(file); } catch { return null; }
  if (stat.size > MAX_BYTES) return null;
  let text;
  try { text = fs.readFileSync(file, 'utf8'); } catch { return null; }
  if (text.indexOf(String.fromCharCode(0)) !== -1) return null;
  if (looksGenerated(text)) return null;
  const ext = path.extname(file).slice(1).toLowerCase();
  const token = budget.LINE_TOKENS[ext];
  const lines = text.split(/\r?\n/);
  const comments = budget.countComments(lines, token);
  const run = budget.longestRun(lines, token);
  const density = lines.length ? comments / lines.length : 0;
  const overRun = run > budget.MAX_RUN;
  const overDensity = lines.length >= budget.DENSITY_FLOOR && density > budget.MAX_DENSITY;
  if (!overRun && !overDensity) return null;
  const allowed = Math.floor(lines.length * budget.MAX_DENSITY);
  return {
    file: file.split(path.sep).join('/'),
    lines: lines.length, comments, run,
    density: Math.round(density * 1000) / 10,
    waste: Math.max(0, comments - allowed),
    reason: overRun && overDensity ? 'run+density' : overRun ? 'run' : 'density',
  };
}

const args = process.argv.slice(2);
const roots = args.filter((a) => !a.startsWith('--') && !/^\d+$/.test(a));
const jsonIdx = args.indexOf('--json');
const topIdx = args.indexOf('--top');
const top = topIdx >= 0 ? Number(args[topIdx + 1]) : 40;

const files = [];
for (const r of roots) walk(path.resolve(r), files);
const hits = files.map(grade).filter(Boolean).sort((a, b) => b.waste - a.waste || b.run - a.run);

const byRepo = new Map();
for (const h of hits) {
  const rel = h.file.replace(/^.*\/skf_s\//, '');
  const repo = rel.split('/')[0];
  const cur = byRepo.get(repo) || { repo, files: 0, waste: 0, worstRun: 0 };
  cur.files += 1; cur.waste += h.waste; cur.worstRun = Math.max(cur.worstRun, h.run);
  byRepo.set(repo, cur);
}

console.log('scanned ' + files.length + ' source files, ' + hits.length + ' over budget');
console.log('\nBY REPO (waste = comment lines above the 20% budget)');
console.log('repo'.padEnd(24) + 'files'.padStart(6) + 'waste'.padStart(8) + 'worstRun'.padStart(10));
for (const r of [...byRepo.values()].sort((a, b) => b.waste - a.waste)) {
  console.log(r.repo.padEnd(24) + String(r.files).padStart(6) + String(r.waste).padStart(8) + String(r.worstRun).padStart(10));
}
console.log('\nTOP ' + top + ' FILES');
console.log('cmt/lines'.padEnd(12) + 'dens'.padStart(6) + 'run'.padStart(5) + '  file');
for (const h of hits.slice(0, top)) {
  console.log((h.comments + '/' + h.lines).padEnd(12) + (h.density + '%').padStart(6) +
    String(h.run).padStart(5) + '  ' + h.file.replace(/^.*\/skf_s\//, ''));
}
if (jsonIdx >= 0) {
  fs.writeFileSync(args[jsonIdx + 1], JSON.stringify(hits, null, 2));
  console.log('\nfull results -> ' + args[jsonIdx + 1]);
}
