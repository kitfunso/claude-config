#!/usr/bin/env node
// Mirrors Claude Code's skills, plugin skills, agents and MCP servers into Antigravity CLI (agy). Claude's files stay the only source.
// Junction safety: remove a junction with fs.rmdirSync or `cmd /c rmdir`, never a recursive delete (it follows into ~/.claude).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { handlersFor, merge } from './claude-hooks.mjs';

const HOME = os.homedir();
const CLAUDE = process.env.NEON_CLAUDE_DIR || path.join(HOME, '.claude');
const GEMINI = process.env.NEON_GEMINI_DIR || path.join(HOME, '.gemini');
const MANIFEST = path.join(GEMINI, 'claude-sync.json');
const readJson = (f, dflt) => { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch { return dflt; } };

/** Claude tool names to agy CLI tool names (agy listed its own tools on 22 Nov: no grep/glob tool, the shell covers them). */
export const AGY_TOOL = {
  Read: 'read_file', Write: 'write_file', Edit: 'edit_file', MultiEdit: 'edit_file', NotebookEdit: 'edit_file',
  Bash: 'run_command', PowerShell: 'run_command', Grep: 'run_command', Glob: 'run_command', LS: 'run_command',
  WebFetch: 'run_command', WebSearch: 'search_web', Agent: 'invoke_subagent', Task: 'invoke_subagent', TodoWrite: 'manage_task',
};

const SKILL_BODY_CAP = 24000; // agy loads only this many bytes of a SKILL.md body (`agy plugin validate`, 22 Nov)

const isLink = (p) => { try { return fs.lstatSync(p).isSymbolicLink(); } catch { return false; } };

/** Removes one entry this script made: a junction (the link only) or a stub folder. Never recursive. */
function removeEntry(p) {
  if (isLink(p)) fs.rmdirSync(p);
  else if (fs.existsSync(p)) { fs.rmSync(path.join(p, 'SKILL.md'), { force: true }); fs.rmdirSync(p); }
}

/** Enabled Claude plugins with their install folders. */
export function enabledPlugins() {
  const enabled = readJson(path.join(CLAUDE, 'settings.json'), {}).enabledPlugins || {};
  const installed = readJson(path.join(CLAUDE, 'plugins', 'installed_plugins.json'), {}).plugins || {};
  return Object.entries(installed)
    .filter(([id]) => enabled[id] === true)
    .map(([id, v]) => ({ id, dir: [].concat(v)[0]?.installPath }))
    .filter((p) => p.dir && fs.existsSync(p.dir));
}

/** Claude's own skills, then enabled plugin skills; Claude's own wins a name clash. */
function skillSources() {
  const found = new Map();
  const add = (dir) => {
    for (const d of fs.existsSync(dir) ? fs.readdirSync(dir) : []) {
      const sd = path.join(dir, d);
      if (!found.has(d.toLowerCase()) && fs.existsSync(path.join(sd, 'SKILL.md'))) found.set(d.toLowerCase(), { name: d, dir: sd });
    }
  };
  add(path.join(CLAUDE, 'skills'));
  for (const p of enabledPlugins()) add(path.join(p.dir, 'skills'));
  return [...found.values()];
}

/** agy's copy of one skill: Claude's frontmatter, its base folder, then the body, or a pointer when the body is too long for agy. */
export function agySkill(dir) {
  const file = path.join(dir, 'SKILL.md');
  const text = fs.readFileSync(file, 'utf8');
  const m = /^(---\r?\n[\s\S]*?\r?\n---)\r?\n?([\s\S]*)$/.exec(text);
  const body = m ? m[2] : text;
  const fwd = file.replace(/\\/g, '/');
  const head = [
    m ? m[1] : `---\nname: ${path.basename(dir)}\ndescription: ${path.basename(dir)}\n---`, '',
    `<!-- Generated by ~/.claude/scripts/neon/sync-agy.mjs from ${fwd}. Edit that file, not this one. -->`,
    `Base directory for this skill: ${path.dirname(fwd)}/ (relative paths in it start there).`, '',
  ].join('\n');
  if (Buffer.byteLength(head + body) <= SKILL_BODY_CAP) return head + body;
  return `${head}This skill is ${Buffer.byteLength(body)} bytes, more than Antigravity loads. Before you act, read ${fwd} in full with read_file (in parts if needed), then follow it.\n`;
}

// agy skips linked skill folders, so each skill is a real folder holding one generated SKILL.md.
function syncSkills(manifest, notes) {
  const root = path.join(GEMINI, 'skills');
  if (isLink(root)) fs.rmdirSync(root);
  fs.mkdirSync(root, { recursive: true });
  const ours = new Set(manifest.skills || []);
  const sources = skillSources();
  if (!sources.length) throw new Error(`no skills found in ${CLAUDE}; agy skills left as they are`);
  const made = [];
  let changed = 0;
  for (const { name, dir } of sources) {
    const dest = path.join(root, name);
    const text = agySkill(dir);
    if (fs.existsSync(dest) || isLink(dest)) {
      if (!ours.has(name)) { notes.push(`left as is (not ours): ${dest}`); continue; }
      if (isLink(dest)) removeEntry(dest);
    }
    made.push(name);
    if (readText(path.join(dest, 'SKILL.md')) === text) continue;
    fs.mkdirSync(dest, { recursive: true });
    fs.writeFileSync(path.join(dest, 'SKILL.md'), text);
    changed++;
  }
  for (const old of ours) if (!made.includes(old)) { removeEntry(path.join(root, old)); notes.push(`removed skill ${old}`); }
  if (changed) notes.push(`skills: ${changed} written, ${made.length} in all`);
  manifest.skills = made;
  delete manifest.pluginSkills;
}

function frontmatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(text);
  if (!m) return { meta: {}, body: text };
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z_-]+):\s*(.*)$/.exec(line);
    if (kv) meta[kv[1]] = kv[2].replace(/^["']|["']$/g, '');
  }
  return { meta, body: m[2] };
}

const agyTool = (t) => (t.startsWith('mcp__') ? 'call_mcp_tool' : AGY_TOOL[t]);

export function agentFile(src, contract = '') {
  const { meta, body } = frontmatter(fs.readFileSync(src, 'utf8'));
  const name = meta.name || path.basename(src, '.md');
  const claudeTools = meta.tools ? meta.tools.split(',').map((t) => t.trim()).filter(Boolean) : [...Object.keys(AGY_TOOL), 'mcp__'];
  const tools = [...new Set(claudeTools.map(agyTool).filter(Boolean))];
  return { name, text: [
    '---',
    `# Generated from ${src} by ~/.claude/scripts/neon/sync-agy.mjs. Edit the Claude file, not this one.`,
    `name: ${JSON.stringify(name)}`,
    `description: ${JSON.stringify(meta.description || name)}`,
    'tools:', ...tools.map((t) => `  - ${t}`),
    'model: inherit',
    'commandExecutionPolicy: auto',
    '---', '', body.trim(), ...(contract ? ['', contract.trim()] : []), '',
  ].join('\n') };
}

/** agy has no SubagentStart event, so the text Claude's SubagentStart hooks give each sub-agent goes into the agent files. */
export function subagentContract() {
  const results = handlersFor('SubagentStart').map((h) => {
    const r = spawnSync(h.command, h.args || [], { input: JSON.stringify({ hook_event_name: 'SubagentStart' }), encoding: 'utf8', shell: !h.args, windowsHide: true, timeout: (h.timeout || 60) * 1000 });
    return { code: r.status, stdout: r.stdout || '', stderr: r.stderr || '' };
  });
  return merge(results, 'SubagentStart').context.join('\n\n');
}

function syncAgents(manifest, notes) {
  const srcDir = path.join(CLAUDE, 'agents');
  if (!fs.existsSync(srcDir)) throw new Error(`no ${srcDir}; agy agents left as they are`);
  const destDir = path.join(GEMINI, 'config', 'agents');
  fs.mkdirSync(destDir, { recursive: true });
  const made = [];
  const contract = subagentContract();
  for (const f of fs.readdirSync(srcDir).filter((x) => x.endsWith('.md'))) {
    const { name, text } = agentFile(path.join(srcDir, f), contract);
    const out = path.join(destDir, `${name}.md`);
    if (fs.existsSync(out) && !(manifest.agents || []).includes(name)) { notes.push(`left as is (not ours): ${out}`); continue; }
    if (readText(out) !== text) { fs.writeFileSync(out, text); notes.push(`agent ${name}`); }
    made.push(name);
  }
  for (const old of manifest.agents || []) {
    if (!made.includes(old)) { fs.rmSync(path.join(destDir, `${old}.md`), { force: true }); notes.push(`removed agent ${old}`); }
  }
  manifest.agents = made;
}

const readText = (f) => { try { return fs.readFileSync(f, 'utf8'); } catch { return null; } };

// agy does not expand ${VAR} in headers, so those servers go through mcp-remote, which does; no secret lands in a file.
export function toAgyServer(v) {
  if (v.command) return { command: v.command, ...(v.args ? { args: v.args } : {}), ...(v.env ? { env: v.env } : {}) };
  if (!v.url || v.type === 'sse') return null;
  const headers = Object.entries(v.headers || {});
  if (!headers.some(([, val]) => String(val).includes('${'))) return { serverUrl: v.url, ...(v.headers ? { headers: v.headers } : {}) };
  return { command: 'npx.cmd', args: ['-y', 'mcp-remote', v.url, ...headers.flatMap(([k, val]) => ['--header', `${k}: ${val}`])] };
}

export function claudeMcpServers() {
  const cj = readJson(path.join(HOME, '.claude.json'), null);
  if (!cj) throw new Error('~/.claude.json unreadable; agy MCP servers left as they are');
  const homeKey = Object.keys(cj.projects || {}).find((k) => path.resolve(k).toLowerCase() === HOME.toLowerCase());
  const servers = { ...(homeKey ? cj.projects[homeKey].mcpServers : {}), ...(cj.mcpServers || {}) };
  for (const p of enabledPlugins()) Object.assign(servers, readJson(path.join(p.dir, '.mcp.json'), {}));
  return servers;
}

function syncMcp(manifest, notes) {
  const file = path.join(GEMINI, 'config', 'mcp_config.json');
  const cfg = readJson(file, {});
  cfg.mcpServers ||= {};
  for (const old of manifest.mcp || []) delete cfg.mcpServers[old];
  const made = [];
  for (const [name, v] of Object.entries(claudeMcpServers())) {
    const s = toAgyServer(v);
    if (!s) { notes.push(`mcp ${name}: skipped (SSE has no agy transport)`); continue; }
    if (cfg.mcpServers[name]) { notes.push(`mcp ${name}: left as is (not ours)`); continue; }
    cfg.mcpServers[name] = s;
    made.push(name);
  }
  const text = `${JSON.stringify(cfg, null, 2)}\n`;
  if (readText(file) !== text) { fs.writeFileSync(file, text); notes.push(`mcp: ${made.join(', ')}`); }
  manifest.mcp = made;
}

export function runSync() {
  const manifest = readJson(MANIFEST, {});
  const notes = [];
  for (const step of [syncSkills, syncAgents, syncMcp]) {
    try { step(manifest, notes); } catch (e) { notes.push(`${step.name} failed: ${e.message}`); }
  }
  fs.writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
  return notes;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const notes = runSync();
  console.log(notes.length ? notes.join('\n') : 'in sync');
}
